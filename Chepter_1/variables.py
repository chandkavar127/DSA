# 2. Swap two variables
# ==========================================

a = 10
b = 20

print("\n----- Program 2 -----")
print("Before Swap:")
print("a =", a)
print("b =", b)

a, b = b, a

print("After Swap:")
print("a =", a)
print("b =", b)


